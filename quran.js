let lastKey = null;

function next() {
  const pool = [
    ...VERSES.map((v) => ({ kind: 'verse', ...v })),
    ...ADHKAR.map((d) => ({ kind: 'dhikr', ...d })),
  ];
  let item;
  do {
    item = pool[Math.floor(Math.random() * pool.length)];
  } while (pool.length > 1 && `${item.kind}:${item.text}` === lastKey);
  lastKey = `${item.kind}:${item.text}`;
  return item;
}

async function post(client, { force = false } = {}) {
  if (!client?.isReady?.()) return;
  const channel = await client.channels.fetch(QURAN_CHANNEL_ID).catch(() => null);
  if (!channel || !channel.isTextBased?.()) return;

  // لا نكرر النشر إذا آخر رسالة جديدة (لو ما كان force)
  if (!force) {
    const last = await channel.messages.fetch({ limit: 1 }).catch(() => null);
    const lastAt = last?.first()?.createdTimestamp || 0;
    if (Date.now() - lastAt < INTERVAL_MS - 60 * 1000) return;
  }

  const item = next();
  const isVerse = item.kind === 'verse';

  await channel
    .send({
      embeds: [
        {
          title: isVerse ? '📖 آية من القرآن الكريم' : '🤲 ذكر',
          description: `**${item.text}**\n\n${item.ref}`,
          color: isVerse ? 0x2ecc71 : 0xf1c40f,
          footer: { text: 'روم القرآن الكريم • تأمّل واذكر الله' },
          timestamp: new Date().toISOString(),
        },
      ],
      allowedMentions: { parse: [] },
    })
    .catch(() => {});
}

function start(client) {
  // أول نشر بعد دقيقة من التشغيل (لو الروم فاضي أو مر عليه وقت)
  setTimeout(() => post(client).catch(() => {}), 60 * 1000);
  const timer = setInterval(() => post(client).catch(() => {}), INTERVAL_MS);
  if (timer.unref) timer.unref();
  return timer;
}

